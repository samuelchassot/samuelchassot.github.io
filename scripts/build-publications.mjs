#!/usr/bin/env node
// Renders res/publications.bib into static HTML inside index.html, between
// the PUBLICATIONS:START / PUBLICATIONS:END markers. Run after editing the bib:
//
//   node scripts/build-publications.mjs
//
// Display metadata comes from non-standard fields in the bib entries
// (ignored by BibTeX tools): venueshort (pill label), pdflocal (local
// PDF path), anchor (stable id used by "Paper" links in Research).
//
// Coauthor homepages are @string entries named homepage_<LastName> (accents
// stripped, e.g. homepage_Kuncak); matching authors get linked.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const BIB_PATH = join(ROOT, 'res/publications.bib');
const HTML_PATH = join(ROOT, 'index.html');
const MY_LAST_NAME = 'Chassot';
const START = '<!-- PUBLICATIONS:START (generated by scripts/build-publications.mjs, do not edit) -->';
const END = '<!-- PUBLICATIONS:END -->';
const INDENT = '            ';

const COMBINING = {
  '`': '̀', "'": '́', '^': '̂', '~': '̃',
  '"': '̈', 'v': '̌', 'c': '̧', '=': '̄',
  '.': '̇', 'u': '̆', 'H': '̋', 'k': '̨'
};

function latexToUnicode(s) {
  const accent = (m, cmd, ch) => ch + (COMBINING[cmd] || '');
  s = s.replace(/\{\\(["'`^~vcuHk=.])\s*\{?([a-zA-Z])\}?\}/g, accent);
  s = s.replace(/\\(["'`^~vcuHk=.])\s*\{?([a-zA-Z])\}?/g, accent);
  s = s.replace(/\\([&%#_])/g, '$1');
  s = s.replace(/[{}]/g, '');
  s = s.replace(/\s+/g, ' ').trim();
  return s.normalize('NFC');
}

function escapeHtml(s) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;')
          .replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

function parseBib(text) {
  // Strip line comments (%) outside of entries.
  text = text.split('\n').filter(l => !/^\s*%/.test(l)).join('\n');
  const entries = [];
  let i = 0;
  while ((i = text.indexOf('@', i)) !== -1) {
    const braceStart = text.indexOf('{', i);
    if (braceStart === -1) break;
    const type = text.slice(i + 1, braceStart).trim().toLowerCase();
    let depth = 1, j = braceStart + 1;
    while (j < text.length && depth > 0) {
      if (text[j] === '{') depth++;
      else if (text[j] === '}') depth--;
      j++;
    }
    const body = text.slice(braceStart + 1, j - 1);
    i = j;
    if (type === 'comment' || type === 'preamble') continue;
    if (type === 'string') {
      entries.push({ type, key: '', fields: parseFields(body) });
      continue;
    }
    const comma = body.indexOf(',');
    const key = body.slice(0, comma).trim();
    entries.push({ type, key, fields: parseFields(body.slice(comma + 1)) });
  }
  return entries;
}

function parseFields(s) {
  const fields = {};
  let i = 0;
  while (i < s.length) {
    const eq = s.indexOf('=', i);
    if (eq === -1) break;
    const name = s.slice(i, eq).replace(/[\s,]/g, '').toLowerCase();
    let j = eq + 1;
    while (j < s.length && /\s/.test(s[j])) j++;
    let value = '';
    if (s[j] === '{') {
      let depth = 1; j++;
      const start = j;
      while (j < s.length && depth > 0) {
        if (s[j] === '{') depth++;
        else if (s[j] === '}') depth--;
        j++;
      }
      value = s.slice(start, j - 1);
    } else if (s[j] === '"') {
      j++;
      const start = j;
      let depth = 0;
      while (j < s.length && !(s[j] === '"' && depth === 0)) {
        if (s[j] === '{') depth++;
        else if (s[j] === '}') depth--;
        j++;
      }
      value = s.slice(start, j);
      j++;
    } else {
      const start = j;
      while (j < s.length && s[j] !== ',') j++;
      value = s.slice(start, j).trim();
    }
    if (name) fields[name] = value;
    while (j < s.length && (s[j] === ',' || /\s/.test(s[j]))) j++;
    i = j;
  }
  return fields;
}

function homepageKey(lastName) {
  return 'homepage_' + lastName.normalize('NFD').replace(/[^a-zA-Z]/g, '').toLowerCase();
}

function formatAuthors(authorField, homepages) {
  const people = latexToUnicode(authorField).split(/\s+and\s+/i);
  return people.map(p => {
    let last, firsts;
    if (p.includes(',')) {
      const parts = p.split(',');
      last = parts[0].trim();
      firsts = (parts[1] || '').trim();
    } else {
      const tokens = p.trim().split(/\s+/);
      last = tokens.pop() || '';
      firsts = tokens.join(' ');
    }
    const initials = firsts.split(/[\s.]+/).filter(Boolean)
      .map(n => n[0].toUpperCase() + '.').join(' ');
    const display = escapeHtml(last + (initials ? ', ' + initials : ''));
    if (last.includes(MY_LAST_NAME)) return '<span class="me">' + display + '</span>';
    const homepage = homepages[homepageKey(last)];
    return homepage
      ? '<a href="' + escapeHtml(homepage) + '" target="_blank">' + display + '</a>'
      : display;
  }).join(', ');
}

function venueLine(f) {
  const parts = [];
  const pages = f.pages ? 'pp. ' + latexToUnicode(f.pages).replace(/\s*--?\s*/, '–') : '';
  if (f.journal) {
    let j = latexToUnicode(f.journal);
    if (f.volume) j += ' ' + f.volume + (f.number ? '(' + f.number + ')' : '');
    parts.push(j);
    if (pages) parts.push(pages);
  } else if (f.booktitle) {
    parts.push(latexToUnicode(f.booktitle));
    if (pages) parts.push(pages);
    if (f.publisher) parts.push(latexToUnicode(f.publisher));
  } else if (f.archiveprefix && f.eprint) {
    parts.push(f.archiveprefix + ':' + f.eprint);
  }
  return parts.join(', ');
}

function renderEntry(e, homepages) {
  const f = e.fields;
  const pdfLocal = (f.pdflocal || '').trim();
  const title = latexToUnicode(f.title || 'Untitled');
  // Springer-style entries carry the DOI as the entry key.
  const doi = (f.doi || (/^10\.\d{4,9}\/\S+$/.test(e.key) ? e.key : '')).trim();
  const doiUrl = doi ? 'https://doi.org/' + doi : '';
  const mainUrl = doiUrl || (f.url || '').trim() || pdfLocal;
  const isArxiv = (f.archiveprefix || '').toLowerCase() === 'arxiv';

  const pill = f.venueshort ? latexToUnicode(f.venueshort) : (isArxiv ? 'Preprint' : '');
  const pillNeutral = isArxiv || e.type === 'misc';

  const links = [];
  if (doiUrl) links.push({ href: doiUrl, label: 'DOI' });
  if (f.url && f.url.trim() !== doiUrl) {
    const u = f.url.trim();
    const label = u.includes('openreview.net') ? 'OpenReview'
      : u.includes('arxiv.org') ? 'arXiv' : 'Link';
    links.push({ href: u, label });
  }
  if (pdfLocal) links.push({ href: pdfLocal, label: 'PDF' });

  const id = (f.anchor || '').trim() || 'pub-' + e.key.replace(/[^a-zA-Z0-9_-]+/g, '-');
  const titleHtml = mainUrl
    ? '<a href="' + escapeHtml(mainUrl) + '" target="_blank">' + escapeHtml(title) + '</a>'
    : escapeHtml(title);

  const meta = [];
  if (f.year) meta.push('<span class="venue-pill year">' + escapeHtml(f.year) + '</span>');
  if (pill) meta.push('<span class="venue-pill' + (pillNeutral ? ' neutral' : '') + '">' + escapeHtml(pill) + '</span>');
  meta.push('<span class="pub-venue">' + escapeHtml(venueLine(f)) + '</span>');
  for (const l of links) {
    meta.push('<a class="link-pill" href="' + escapeHtml(l.href) + '" target="_blank">' + l.label + '</a>');
  }

  return [
    '<li class="pub-card" id="' + escapeHtml(id) + '">',
    '  <div class="pub-title">' + titleHtml + '</div>',
    '  <div class="pub-authors">' + formatAuthors(f.author || '', homepages) + '</div>',
    '  <div class="meta-row">',
    ...meta.map(m => '    ' + m),
    '  </div>',
    '</li>'
  ];
}

const parsed = parseBib(readFileSync(BIB_PATH, 'utf8'));
const homepages = {};
for (const s of parsed.filter(e => e.type === 'string')) {
  for (const [name, value] of Object.entries(s.fields)) {
    if (name.startsWith('homepage_')) homepages[name] = value.trim();
  }
}

const entries = parsed
  .filter(e => e.type !== 'string')
  .map((e, idx) => ({ e, idx }))
  .sort((a, b) => (parseInt(b.e.fields.year) || 0) - (parseInt(a.e.fields.year) || 0) || a.idx - b.idx)
  .map(x => x.e);

const lines = entries.flatMap(e => renderEntry(e, homepages)).map(l => INDENT + l);
const html = readFileSync(HTML_PATH, 'utf8');
const s = html.indexOf(START), t = html.indexOf(END);
if (s === -1 || t === -1 || t < s) {
  console.error('Publication markers not found in index.html');
  process.exit(1);
}
const out = html.slice(0, s + START.length) + '\n' + lines.join('\n') + '\n' + INDENT + html.slice(t);
writeFileSync(HTML_PATH, out);
console.log('Rendered ' + entries.length + ' publications into index.html');
